#!/usr/bin/env bash
# Fallback for hosts where the web folder (public_html) cannot be a link to
# the app's public/ folder: copy public/ into it and write an index.php that
# loads the app from its folder outside the web root.
#
#   scripts/publish-public.sh <web-folder>
#   e.g. scripts/publish-public.sh ~/domains/example.com/public_html
#
# Run again after every update (update.sh does it when PUBLIC_COPY_DIR
# is set in ~/.school-saas/install.env).
set -euo pipefail

TARGET="${1:?usage: publish-public.sh <web-folder>}"
APP="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

[[ -d "$TARGET" ]] || { echo "publish: $TARGET is not a folder" >&2; exit 1; }
[[ -L "$TARGET" ]] && { echo "publish: $TARGET is a link; nothing to copy" >&2; exit 1; }
case "$TARGET" in "$APP"|"$APP"/*) echo "publish: target must be outside the app folder" >&2; exit 1;; esac

# Old hashed assets are removed so the folder does not grow on every update.
rm -rf "$TARGET/build"
cp -a "$APP/public/." "$TARGET/"

cat > "$TARGET/index.php" <<PHP
<?php
// Generated by scripts/publish-public.sh — the app lives outside the web folder.
use Illuminate\Http\Request;

define('LARAVEL_START', microtime(true));
\$base = '$APP';

if (file_exists(\$maintenance = \$base.'/storage/framework/maintenance.php')) {
    require \$maintenance;
}

require \$base.'/vendor/autoload.php';

\$app = require_once \$base.'/bootstrap/app.php';
\$app->usePublicPath(__DIR__);
\$app->handleRequest(Request::capture());
PHP

echo "publish: $APP/public copied to $TARGET"
